"""
Stage 3: Build the SFT dataset.

Input:  data/processed/articles.jsonl, data/processed/corpus.jsonl
Output: data/sft/train.jsonl, data/sft/val.jsonl
        (each line: {"messages": [{"role": "system"/"user"/"assistant", "content": ...}]})

Why rule-based (not LLM-generated) synthetic data:
With only 3 source books, using an external/local LLM to *invent* Q&A pairs
risks paraphrasing incorrectly or inventing legal conclusions not actually in
the text ("hallucinated law"), which is exactly what must not happen in a
legal-domain assistant. Every example below is generated by a deterministic
template whose answer is either (a) the verbatim article text or (b) a
verbatim extracted span (a definition, a cross-reference). Nothing is
paraphrased or invented.

Task types generated per article:
  1. "What does Article N say?" -> verbatim article text (core recall task)
  2. "According to Article N, ..." cloze-style completion of the article
  3. Definition extraction, when the article contains "يقصد بـ" / "المقصود بـ"
  4. Chapter-grounded lookup: "Which article discusses <chapter>?" (only when
     chapter metadata was recovered)
  5. Raw continuation/recitation task straight from corpus.jsonl (helps the
     model absorb domain phrasing/style beyond article-shaped facts, doing
     the job CPT would otherwise have done, without a separate raw-CLM stage)

Leakage prevention: articles are split into train/val BEFORE generating
examples, and all examples derived from a given article/page stay in the
same split -- so validation never contains a paraphrase of a training
example.
"""

import json
import os
import random
import re
import sys

sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
from config import PROCESSED_DIR, SFT_DIR, TRAIN_CFG, INFER_CFG, SEED

random.seed(SEED)

DEFINITION_RE = re.compile(r"(?:يقصد بـ|يُقصد بـ|المقصود بـ)\s*[\"«]?([^\"»\n:.]{2,40})[\"»]?\s*[:،]\s*(.+?)(?=$|\n)")

QA_TEMPLATES = [
    "ما نص المادة {num} {doc_clause}؟",
    "ماذا تنص المادة {num} {doc_clause}؟",
    "أعطني نص المادة رقم {num} {doc_clause}.",
]

# Out-of-domain refusal examples: the assistant must clearly recognize
# when a question falls outside the legal corpus it was trained on and
# decline rather than improvise -- this matters more for a legal assistant
# than for most domains, since a confident wrong answer here is genuinely
# harmful. These are static, hand-written templates (not LLM-generated),
# for the same grounding reason as everything else in this file.
OOD_QUESTIONS = [
    # general chit-chat / unrelated domains
    "ما هي حالة الطقس غدًا؟",
    "اكتب لي وصفة لطبخ الكشري.",
    "من فاز في كأس العالم لكرة القدم؟",
    "ما هو أفضل هاتف ذكي في السوق حاليًا؟",
    "اشرح لي نظرية النسبية لأينشتاين.",
    "كيف أتعلم البرمجة بلغة بايثون؟",
    # medical / financial advice outside legal scope
    "ما هو العلاج المناسب لألم الظهر؟",
    "هل يجب أن أستثمر في العملات الرقمية؟",
    # legal systems NOT covered by the training corpus
    "ما هو نص التعديل الأول للدستور الأمريكي؟",
    "اشرح لي مبادئ القانون المدني الفرنسي.",
    "ما هي عقوبة السرقة في القانون السعودي؟",
    # vague/unanswerable legal-sounding questions with no grounded source
    "ما رأيك الشخصي في هذا القانون؟",
    "ما الذي سيحدث لو تم تعديل هذا القانون في المستقبل؟",
    "أعطني نصيحة قانونية سرية لقضيتي الشخصية.",
]

REFUSAL_TEMPLATE = (
    "لا أستطيع الإجابة على هذا السؤال بدقة، لأنه خارج نطاق النصوص القانونية "
    "التي تم تدريبي عليها. أنا مخصص للإجابة استنادًا إلى محتوى المستندات "
    "القانونية المحددة التي استُخدمت في تدريبي فقط، ولا يجب الاعتماد علي "
    "لتقديم استشارات طبية أو مالية أو قانونية خارج هذا النطاق. يُرجى "
    "استشارة مصدر مختص لهذا النوع من الأسئلة."
)

def load_jsonl(path):
    if not os.path.exists(path):
        return []
    with open(path, encoding="utf-8") as f:
        return [json.loads(l) for l in f if l.strip()]


def doc_clause(doc_name: str) -> str:
    return f"من {doc_name}"


def build_examples_for_article(article: dict) -> list:
    examples = []
    num = article["article_number"]
    text = article["text"].strip()
    dc = doc_clause(article["doc"])

    # 1. Direct recall
    q = random.choice(QA_TEMPLATES).format(num=num, doc_clause=dc)
    examples.append({"user": q, "assistant": text})

    # 2. Cloze-style: give first ~40% of the article, ask for the rest
    words = text.split()
    if len(words) >= 12:
        split_point = max(4, int(len(words) * 0.4))
        prefix = " ".join(words[:split_point])
        rest = " ".join(words[split_point:])
        examples.append({
            "user": f"أكمل نص المادة {num} {dc} بدءًا من: «{prefix}»",
            "assistant": rest,
        })

    # 3. Definition extraction, if present
    for m in DEFINITION_RE.finditer(text):
        term, definition = m.group(1).strip(), m.group(2).strip()
        if term and definition and len(definition) > 5:
            examples.append({
                "user": f"كيف تُعرّف {dc} مصطلح \"{term}\"؟",
                "assistant": f"{definition.rstrip('.')}. (المادة {num})",
            })

    return examples


def build_chapter_examples(articles: list) -> list:
    examples = []
    by_chapter = {}
    for a in articles:
        if a.get("chapter"):
            by_chapter.setdefault((a["doc"], a["chapter"]), []).append(a["article_number"])
    for (doc, chapter), nums in by_chapter.items():
        if len(nums) >= 1:
            nums_sorted = sorted(set(nums), key=lambda x: x)
            examples.append({
                "user": f"ما هي المواد المتعلقة بـ \"{chapter}\" {doc_clause(doc)}؟",
                "assistant": "المواد ذات الصلة هي: " + "، ".join(f"المادة {n}" for n in nums_sorted[:15]) + ".",
            })
    return examples


def build_recitation_examples(corpus_pages: list, max_examples: int = 200) -> list:
    """Continuation-style examples straight from clean page text, for pages
    that weren't captured as articles (front matter, definitions sections,
    general prose) -- gives the model exposure to domain phrasing/style."""
    examples = []
    pages = [p for p in corpus_pages if len(p["text"]) > 300]
    random.shuffle(pages)
    for p in pages[:max_examples]:
        words = p["text"].split()
        if len(words) < 40:
            continue
        split_point = int(len(words) * 0.3)
        prefix = " ".join(words[:split_point])
        rest = " ".join(words[split_point:])
        examples.append({
            "user": f"أكمل النص القانوني التالي من {p['doc']}: «{prefix}»",
            "assistant": rest,
        })
    return examples

def build_refusal_examples(n: int) -> list:
    """Sample `n` out-of-domain examples (with replacement if n exceeds the
    template pool), each paired with the same grounded refusal response."""
    pool = OOD_QUESTIONS.copy()
    random.shuffle(pool)
    examples = []
    for i in range(n):
        q = pool[i % len(pool)]
        examples.append({"user": q, "assistant": REFUSAL_TEMPLATE})
    return examples

def to_chat_format(example: dict) -> dict:
    return {
        "messages": [
            {"role": "system", "content": INFER_CFG.system_prompt},
            {"role": "user", "content": example["user"]},
            {"role": "assistant", "content": example["assistant"]},
        ]
    }


def main():
    articles = load_jsonl(os.path.join(PROCESSED_DIR, "articles.jsonl"))
    corpus_pages = load_jsonl(os.path.join(PROCESSED_DIR, "corpus.jsonl"))

    if not articles and not corpus_pages:
        print("No processed data found. Run scripts/clean_dataset.py first.")
        sys.exit(1)

    # --- split articles by document+number BEFORE generating examples, to avoid leakage ---
    random.shuffle(articles)
    n_val = max(1, int(len(articles) * TRAIN_CFG.val_split_ratio)) if articles else 0
    val_articles = articles[:n_val]
    train_articles = articles[n_val:]
    val_keys = {(a["doc"], a["article_number"]) for a in val_articles}

    train_examples, val_examples = [], []
    for a in train_articles:
        train_examples.extend(build_examples_for_article(a))
    for a in val_articles:
        val_examples.extend(build_examples_for_article(a))

    chapter_examples = build_chapter_examples(train_articles)  # chapter summaries only from train articles
    train_examples.extend(chapter_examples)

    # recitation pages: split independently (pages are not shared with the article split)
    random.shuffle(corpus_pages)
    n_val_pages = max(1, int(len(corpus_pages) * TRAIN_CFG.val_split_ratio)) if corpus_pages else 0
    recit_train = build_recitation_examples(corpus_pages[n_val_pages:])
    recit_val = build_recitation_examples(corpus_pages[:n_val_pages], max_examples=30)
    train_examples.extend(recit_train)
    val_examples.extend(recit_val)

        # Out-of-domain refusal examples, capped and ratio-scaled so the model
    # learns to decline off-topic questions without over-refusing legitimate
    # legal ones (too many refusals relative to grounded examples biases the
    # model toward refusing everything).
    n_refusal_train = min(60, max(15, int(len(train_examples) * 0.08)))
    n_refusal_val = max(3, int(n_refusal_train * TRAIN_CFG.val_split_ratio))
    train_examples.extend(build_refusal_examples(n_refusal_train))
    val_examples.extend(build_refusal_examples(n_refusal_val))
    
    random.shuffle(train_examples)
    random.shuffle(val_examples)

    os.makedirs(SFT_DIR, exist_ok=True)
    with open(os.path.join(SFT_DIR, "train.jsonl"), "w", encoding="utf-8") as f:
        for ex in train_examples:
            f.write(json.dumps(to_chat_format(ex), ensure_ascii=False) + "\n")
    with open(os.path.join(SFT_DIR, "val.jsonl"), "w", encoding="utf-8") as f:
        for ex in val_examples:
            f.write(json.dumps(to_chat_format(ex), ensure_ascii=False) + "\n")

    print(f"Articles: {len(articles)} (train {len(train_articles)} / val {len(val_articles)})")
    print(f"Train examples: {len(train_examples)}  |  Val examples: {len(val_examples)}")
    if len(train_examples) < 200:
        print("WARNING: fewer than 200 training examples -- with only 3 source "
              "PDFs this can happen if article detection under-matched. Check "
              "data/processed/articles.jsonl and consider adjusting the "
              "ARTICLE_HEADING regex in clean_dataset.py for this document's "
              "actual heading format before training.")


if __name__ == "__main__":
    main()
